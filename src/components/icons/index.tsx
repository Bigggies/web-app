export function TxIcon({ category }: { category: string }) {
  const c = '#6B7280', s = 18
  if (category === 'Groceries') return <IconShoppingCart size={s} color={c} />
  if (category === 'Transport') return <IconCar size={s} color={c} />
  if (category === 'Utilities') return <IconZap size={s} color={c} />
  if (category === 'Food & Drink') return <IconCoffee size={s} color={c} />
  if (category === 'Income') return <IconBriefcase size={s} color={c} />
  if (category === 'Shopping') return <IconTag size={s} color={c} />
  return <IconSmartphone size={s} color={c} />
}

export function GoalIcon({ name, done }: { name: string; done: boolean }) {
  const c = done ? '#059669' : '#6B7280', s = 18
  if (name === 'Emergency Fund') return <IconShield size={s} color={c} />
  if (name === 'Holiday Trip') return <IconPlane size={s} color={c} />
  return <IconMonitor size={s} color={c} />
}
